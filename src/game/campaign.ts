import { gameMissions } from './gameData.ts';
import { initialRangeState, type RangeState } from './terminalEngine.ts';

export const augmentations = [
  { id: 'damping', name: 'TRACE DAMPER', cost: 80, description: 'Halves trace generated by invalid range commands.', type: 'upgrade' },
  { id: 'recovery', name: 'SIGNAL RECOVERY', cost: 120, description: 'Unlocks recover: remove 30 trace once per deployment.', type: 'skill' },
  { id: 'analysis', name: 'ANALYSIS ASSIST', cost: 100, description: 'Displays the exact next investigation command in the range.', type: 'skill' },
  { id: 'archive', name: 'DEEP ARCHIVE', cost: 150, description: 'Decrypts an additional handler dossier in the database.', type: 'upgrade' },
] as const;
export interface Campaign {
  version: 1; completed: string[]; active: string; ranges: Record<string, RangeState>;
  augments: string[]; ending: 'preserve' | 'release' | null; notes: string;
  diagnostics: boolean; channel: boolean;
}
export const newCampaign = (): Campaign => ({ version: 1, completed: [], active: 'B01', ranges: {}, augments: [], ending: null, notes: '', diagnostics: false, channel: true });
export const isUnlocked = (campaign: Campaign, id: string) => {
  const index = gameMissions.findIndex(m => m.id === id);
  return index >= 0 && (index === 0 || campaign.completed.includes(gameMissions[index - 1].id));
};
export const campaignXP = (campaign: Campaign) => gameMissions.filter(m => campaign.completed.includes(m.id)).reduce((xp, m) => xp + m.rewardXP, 0);
export const credits = (campaign: Campaign) => Math.floor(campaignXP(campaign) / 5) - augmentations.filter(a => campaign.augments.includes(a.id)).reduce((sum, a) => sum + a.cost, 0);
export function purchase(campaign: Campaign, id: string): Campaign {
  const item = augmentations.find(a => a.id === id);
  if (!item || campaign.augments.includes(id) || credits(campaign) < item.cost) return campaign;
  return { ...campaign, augments: [...campaign.augments, id] };
}
export function completeMission(campaign: Campaign, id: string): Campaign {
  const mission = gameMissions.find(m => m.id === id);
  if (!mission || !isUnlocked(campaign, id) || campaign.completed.includes(id) || campaign.ranges[id]?.discoveredFlag !== mission.flag) return campaign;
  return { ...campaign, completed: [...campaign.completed, id] };
}
export function parseCampaign(raw: string | null): Campaign {
  const clean = newCampaign();
  if (!raw) return clean;
  try {
    const data = JSON.parse(raw);
    if (!data || typeof data !== 'object') return clean;
    // Only contiguous, known completions can unlock the campaign.
    for (const m of gameMissions) { if (Array.isArray(data.completed) && data.completed.includes(m.id)) clean.completed.push(m.id); else break; }
    if (typeof data.active === 'string' && isUnlocked(clean, data.active)) clean.active = data.active;
    for (const mission of gameMissions) {
      const state = data.ranges?.[mission.id];
      if (!state || !isUnlocked(clean, mission.id)) continue;
      const steps = Number.isInteger(state.completedSteps) ? Math.max(0, Math.min(mission.objectives.length, state.completedSteps)) : 0;
      clean.ranges[mission.id] = { ...initialRangeState(), completedSteps: steps,
        currentDirectory: typeof state.currentDirectory === 'string' ? state.currentDirectory.slice(0, 100) : '~',
        discoveredFlag: steps === mission.objectives.length && state.discoveredFlag === mission.flag ? mission.flag : null,
        trace: Number.isFinite(state.trace) ? Math.max(0, Math.min(100, state.trace)) : 0, recovered: state.recovered === true };
    }
    for (const a of augmentations) if (Array.isArray(data.augments) && data.augments.includes(a.id) && credits(clean) >= a.cost) clean.augments.push(a.id);
    if (clean.completed.length === gameMissions.length && ['preserve', 'release'].includes(data.ending)) clean.ending = data.ending;
    clean.notes = typeof data.notes === 'string' ? data.notes.slice(0, 12000) : '';
    clean.diagnostics = data.diagnostics === true; clean.channel = data.channel !== false;
    return clean;
  } catch { return clean; }
}
